<?php

declare(strict_types=1);

namespace SuperKernel\Di\Provider;

use Psr\Container\ContainerInterface as PsrContainerInterface;
use SuperKernel\Annotator\Cache\AnnotationCache;
use SuperKernel\Annotator\Exception\AnnotationCacheException;
use SuperKernel\Attribute\FactoryProvider;
use SuperKernel\Contract\AnnotationCollectorInterface;
use SuperKernel\Contract\BasePathInterface;
use SuperKernel\Contract\ContainerInterface;
use SuperKernel\Contract\PackageManagerInterface;
use SuperKernel\Contract\ReflectorInterface;
use SuperKernel\Contract\VendorDirInterface;
use SuperKernel\Di\Container;
use SuperKernel\Metadata\Exception\BuildRequiredException;
use SuperKernel\Metadata\Exception\MetadataException;
use SuperKernel\Metadata\Provider\BasePathProvider;
use SuperKernel\Metadata\Provider\PackageManagerProvider;
use SuperKernel\Metadata\Provider\VendorDirProvider;
use SuperKernel\Reflector\Provider\ReflectorProvider;
use Throwable;

#[
    FactoryProvider(ContainerInterface::class),
    FactoryProvider(PsrContainerInterface::class),
]
final readonly class ContainerProvider
{
    /**
     * Returns the supplied container unchanged, or restores the metadata generated by `skernel build` and returns a
     * new root container. Restoration only reads generated files; it never scans sources or reads Composer files.
     *
     * @throws BuildRequiredException When the generated package metadata or annotation records are missing, invalid,
     *                                or out of date
     * @throws MetadataException      When no registered Composer class loader serves super-kernel/metadata
     * @throws Throwable              When a restored Attribute or the reflector cannot be constructed
     */
    public function __invoke(?PsrContainerInterface $container = null): PsrContainerInterface
    {
        if (null !== $container) {
            return $container;
        }

        $vendorDir = new VendorDirProvider()();
        $basePath = new BasePathProvider()($vendorDir);
        $packages = new PackageManagerProvider()($vendorDir, $basePath);

        try {
            $collector = new AnnotationCache($vendorDir)->read($packages);
        } catch (AnnotationCacheException $exception) {
            throw new BuildRequiredException('The generated annotation records cannot be restored.', $exception);
        }

        /** @var array<class-string, object> $entries */
        $entries = [
            AnnotationCollectorInterface::class => $collector,
            BasePathInterface::class            => $basePath,
            PackageManagerInterface::class      => $packages,
            ReflectorInterface::class           => new ReflectorProvider()(),
            VendorDirInterface::class           => $vendorDir,
        ];

        foreach ($entries as $entry) {
            $entries[$entry::class] = $entry;
        }

        return new Container($collector, $entries);
    }
}
